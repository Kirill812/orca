const fs = require('fs')
const path = require('path')
const { withDangerousMod, withMainActivity, withMainApplication } = require('expo/config-plugins')

// Why: React Native converts dp<->px with the display's real density (getRealMetrics in
// DisplayMetricsHolder / PixelUtil), while the app's Resources can carry a different, per-app
// density — BOOX EinkWise's DPI setting does exactly that. Layout and drawing then disagree and
// the UI overflows (or underfills) the physical screen, with clipped text. Aligning the app's
// density with the display's keeps both sides consistent. A stock Android "Display size" change
// moves both together, so it is untouched. RN ships prebuilt on Android, so this is fixed at the
// app's context instead of in PixelUtil.
const HELPER_CLASS = 'OrcaDisplayDensity'
const MARKER = `${HELPER_CLASS}.wrap(`

function helperSource(packageName) {
  return `package ${packageName}

import android.content.Context
import android.content.res.Configuration
import android.content.res.Resources

// Generated by plugins/android-align-display-density.js — see the reason there.
object ${HELPER_CLASS} {
  fun wrap(base: Context): Context {
    // Why Resources.getSystem(): it carries the display's density without the per-app
    // override, and needs no Display lookup — an Activity's base context can't resolve one
    // yet inside attachBaseContext.
    val real = Resources.getSystem().displayMetrics
    val current = base.resources.configuration
    if (real.densityDpi <= 0 || current.densityDpi == real.densityDpi) return base
    val aligned = Configuration(current)
    aligned.densityDpi = real.densityDpi
    return base.createConfigurationContext(aligned)
  }
}
`
}

/** Adds an attachBaseContext override routing through the helper to a Kotlin class body. */
function injectAttachBaseContext(source, className) {
  if (source.includes(MARKER)) {
    return source
  }
  const header = new RegExp(`class ${className}\\b[^{]*\\{`)
  const match = header.exec(source)
  if (!match) {
    throw new Error(`android-align-display-density: class ${className} not found`)
  }
  const override = `
  override fun attachBaseContext(base: android.content.Context) {
    super.attachBaseContext(${HELPER_CLASS}.wrap(base))
  }
`
  const end = match.index + match[0].length
  return source.slice(0, end) + override + source.slice(end)
}

function withAndroidAlignDisplayDensity(config) {
  config = withMainActivity(config, (cfg) => {
    cfg.modResults.contents = injectAttachBaseContext(cfg.modResults.contents, 'MainActivity')
    return cfg
  })
  config = withMainApplication(config, (cfg) => {
    cfg.modResults.contents = injectAttachBaseContext(cfg.modResults.contents, 'MainApplication')
    return cfg
  })
  return withDangerousMod(config, [
    'android',
    (cfg) => {
      const packageName = cfg.android?.package
      if (!packageName) {
        throw new Error('android-align-display-density: android.package is not set')
      }
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        'app/src/main/java',
        ...packageName.split('.')
      )
      fs.mkdirSync(dir, { recursive: true })
      fs.writeFileSync(path.join(dir, `${HELPER_CLASS}.kt`), helperSource(packageName))
      return cfg
    }
  ])
}

module.exports = withAndroidAlignDisplayDensity
module.exports.injectAttachBaseContext = injectAttachBaseContext
